#!/usr/bin/env python3
"""Generate a compile-bound Bazel workload for cache measurements.

exp01's three source files build in ~1s, which is Bazel's fixed overhead, not
compilation. A cache experiment on that workload measures nothing. This script
generates N translation units that are genuinely slow to compile (<regex> is
the classic offender) so that compile time dominates the wall clock and the
cache actually has something to save.

Generated output is git-ignored: it is reproducible from this script, and
committing 40 machine-written files would bury the repo's real content.
"""

import argparse

NL = chr(10)
from pathlib import Path

HEADER = """#ifndef WORKLOAD_LIB_{n:03d}_H_
#define WORKLOAD_LIB_{n:03d}_H_

#include <string>

namespace workload {{
std::string Run{n:03d}(const std::string& input);
}}  // namespace workload

#endif
"""

# <regex> is slow to compile on purpose - that is the point of the workload.
SOURCE = """#include "experiments/exp02_remote_cache/workload/lib_{n:03d}.h"

#include <regex>
#include <sstream>
#include <vector>
#include <algorithm>

namespace workload {{

namespace {{
template <int N>
struct Fib {{ static constexpr long value = Fib<N - 1>::value + Fib<N - 2>::value; }};
template <> struct Fib<0> {{ static constexpr long value = 0; }};
template <> struct Fib<1> {{ static constexpr long value = 1; }};
}}  // namespace

std::string Run{n:03d}(const std::string& input) {{
  static const std::regex pattern(R"(([a-z]+)[-_]?([0-9]*))");
  std::smatch m;
  std::ostringstream out;
  out << "lib{n:03d}:" << Fib<{fib}>::value << ":";
  if (std::regex_search(input, m, pattern)) {{
    out << m[1].str();
  }}
  std::vector<int> v{{{n}, {n} * 2, {n} * 3}};
  std::sort(v.begin(), v.end(), std::greater<int>());
  out << ":" << v.front();
  return out.str();
}}

}}  // namespace workload
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=40)
    args = ap.parse_args()

    out = Path(__file__).resolve().parent / "workload"
    out.mkdir(exist_ok=True)
    for old in out.glob("*"):
        old.unlink()

    names = []
    for n in range(args.count):
        (out / f"lib_{n:03d}.h").write_text(HEADER.format(n=n), encoding="utf-8")
        (out / f"lib_{n:03d}.cc").write_text(
            SOURCE.format(n=n, fib=20 + (n % 5)), encoding="utf-8"
        )
        names.append(f"lib_{n:03d}")

    rules = []
    for name in names:
        rules.append(
            f'cc_library(\n'
            f'    name = "{name}",\n'
            f'    srcs = ["{name}.cc"],\n'
            f'    hdrs = ["{name}.h"],\n'
            f')\n'
        )
    deps = ",\n".join(f'        ":{n}"' for n in names)
    rules.append(
        'cc_binary(\n'
        '    name = "all_workload",\n'
        '    srcs = ["main.cc"],\n'
        '    deps = [\n' + deps + ',\n'
        '    ],\n'
        ')\n'
    )

    main_includes = "\n".join(
        f'#include "experiments/exp02_remote_cache/workload/{n}.h"' for n in names
    )
    calls = "\n".join(
        f'  total += workload::Run{n.split("_")[1]}("probe-{i}").size();'
        for i, n in enumerate(names)
    )
    (out / "main.cc").write_text(
        "#include <cstddef>" + NL + "#include <iostream>" + NL +
        "#include <string>" + NL + NL + main_includes + NL + NL +
        "int main() {" + NL + "  size_t total = 0;" + NL + calls + NL +
        '  std::cout << "total=" << total << std::endl;' + NL +
        "  return 0;" + NL + "}" + NL,
        encoding="utf-8",
    )
    (out / "BUILD.bazel").write_text(
        "# GENERATED by gen_workload.py - do not edit, do not commit.\n\n"
        + "\n".join(rules),
        encoding="utf-8",
    )
    print(f"generated {args.count} libraries in {out}")


if __name__ == "__main__":
    main()
